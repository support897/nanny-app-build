// Desk generator (never ships): walks the journey data and emits
// lang-q.js, the English question registry for the language layer.
// A field id used by BOTH sides with different words is qualified
// by side (q.family.X / q.carer.X); shared words share one key.
import { FAMILY_PAGES, CARER_PAGES } from "./questions.js";
import { EXPANSION } from "./questions2.js";
import { writeFileSync } from "node:fs";
const seen = new Map(); // code -> {label, options, sides:Set}
const collect = (pages, side) => {
  for (const p of pages) for (const f of p.fields) {
    const code = f.pair || f.id;
    const sig = JSON.stringify([f.label, f.options || []]);
    if (!seen.has(code)) seen.set(code, { sig, sides: new Set([side]) });
    else { const e = seen.get(code); e.sides.add(side); if (e.sig !== sig) e.clash = true; }
  }
};
collect(FAMILY_PAGES, "family"); collect(CARER_PAGES, "carer");
collect(EXPANSION.family, "family"); collect(EXPANSION.carer, "carer");
export const keyOf = (code, side) => (seen.get(code)?.clash ? `q.${side}.${code}` : `q.${code}`);
const out = {};
const walk = (pages, side, pagePrefix) => {
  pages.forEach((p, pi) => {
    out[`page.${pagePrefix}.${pi}`] = p.title;
    for (const f of p.fields) {
      const code = f.pair || f.id;
      const base = keyOf(code, side);
      out[base] = f.label;
      (f.options || []).forEach((o, oi) => { out[`${base}.o${oi}`] = o; });
    }
  });
};
walk(FAMILY_PAGES, "family", "family"); walk(CARER_PAGES, "carer", "carer");
walk(EXPANSION.family, "family", "familyx"); walk(EXPANSION.carer, "carer", "carerx");
const body = "// GENERATED by lang-gen.mjs from questions.js + questions2.js.\n// English is the source of truth; regenerate, never hand edit.\nexport const Q_EN = " + JSON.stringify(out, null, 1) + ";\n";
writeFileSync(new URL("./lang-q.js", import.meta.url), body);
console.log("keys:", Object.keys(out).length, "clashes:", [...seen.values()].filter((e) => e.clash).length);
